# Regenerates src/topics/fixtures/gutenberg_test.j: two real-world books for
# the overlays, as base64 constants (the overlays run from a copy of src/
# alone, so a fixture cannot be a file beside them).
#
# Source: Project Gutenberg eBook #1080, Jonathan Swift, "A Modest Proposal"
# (public domain in the USA), https://www.gutenberg.org/ebooks/1080, in its
# EPUB 3 (.epub3.images) and older EPUB 2 (.epub.noimages) downloads. The
# Project Gutenberg licence they carry permits redistribution. Trimmed: the
# cover JPEG is replaced by an 8x8 one, everything else is kept as
# downloaded (the archives are rewritten with the same entries, in the same
# order, `mimetype` first and stored).
#
# Needs curl, python3 and network access; not run in CI. A rerun fetches
# Gutenberg's current files, which it regenerates from time to time, so the
# overlay's expectations may need updating with the fixture.
#
# Usage: tools/build-fixtures.sh
set -euo pipefail
cd "$(dirname "$0")/.."

work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

curl -fsSL -o "$work/epub3.epub" https://www.gutenberg.org/ebooks/1080.epub3.images
curl -fsSL -o "$work/epub2.epub" https://www.gutenberg.org/ebooks/1080.epub.noimages

python3 -I - "$work" src/topics/fixtures/gutenberg_test.j <<'PY'
