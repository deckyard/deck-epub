    "cRQygZGhCCNCscEVUtHwJDNicoIJChYXGBkaJSYnKCkqNDU2Nzg5OkNERUZHSElKU1RVVldY"
    "WVpjZGVmZ2hpanN0dXZ3eHl6g4SFhoeIiYqSk5SVlpeYmZqio6Slpqeoqaqys7S1tre4ubrC"
    "w8TFxsfIycrS09TV1tfY2drh4uPk5ebn6Onq8fLz9PX29/j5+v/aAAgBAQAAPwAr/9k=")

def trimmed(path):
    src = zipfile.ZipFile(path)
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w") as dst:
        for info in src.infolist():
            data = src.read(info.filename)
            if info.filename.lower().endswith((".jpg", ".jpeg")):
                data = TINY_JPEG
            method = zipfile.ZIP_STORED if info.filename == "mimetype" else zipfile.ZIP_DEFLATED
            entry = zipfile.ZipInfo(info.filename, date_time=(2026, 1, 1, 0, 0, 0))
            entry.compress_type = method
            dst.writestr(entry, data)
    return buf.getvalue()

def constant(name, data):
    text = base64.b64encode(data).decode()
    rows = [text[i:i + 76] for i in range(0, len(text), 76)]
    body = ",\n".join('    "%s"' % r for r in rows)
    return "def const %s as list of string init [\n%s\n];\n" % (name, body)

header = """# SPDX-License-Identifier: LGPL-3.0-only
# SPDX-FileCopyrightText: Copyright (C) 2026 mplx <mplx@jennifer-lang.dev>
# pragma-jennifer-version: >=0.26.0

# epub - Project Gutenberg eBook #1080 (Jonathan Swift, "A Modest Proposal",
# public domain in the USA, https://www.gutenberg.org/ebooks/1080) in its
# EPUB 3 and EPUB 2 downloads, cover image shrunk, as base64 for the overlays.
# Generated by tools/build-fixtures.sh. Do not edit.

"""
with open(out, "w") as f:
    f.write(header)
    f.write(constant("GUTENBERG_EPUB3_BASE64", trimmed(work + "/epub3.epub")))
    f.write("\n")
    f.write(constant("GUTENBERG_EPUB2_BASE64", trimmed(work + "/epub2.epub")))
PY
echo "wrote src/topics/fixtures/gutenberg_test.j"
